// Team Brain slice 1 — typed errors for ledger lifecycle guards.
// Every guard rejection carries a stable machine-readable `code` so tests and
// callers can assert the exact failure instead of matching message text.

export class TeamBrainError extends Error {
  constructor(code, message, details = {}) {
    super(message);
    this.name = "TeamBrainError";
    this.code = code;
    this.details = details;
  }
}

